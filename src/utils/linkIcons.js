/**
 * Best-guess icon key for a user-defined link from its label and URL.
 * Falls back to the generic website (globe) icon.
 */
export function iconKeyFor(label = '', url = '') {
  const l = String(label).toLowerCase().trim()
  const u = String(url).toLowerCase().trim()
  const hay = `${l} ${u}`
  if (u.startsWith('mailto:') || /\be-?mail\b/.test(l)) return 'email'
  if (u.startsWith('tel:') || /\b(mobile|phone|cell|whatsapp|call)\b/.test(l)) return 'phone'
  if (/github\.com|\bgithub\b/.test(hay)) return 'github'
  if (/linkedin\.com|\blinkedin\b/.test(hay)) return 'linkedin'
  if (/medium\.com|\bmedium\b/.test(hay)) return 'medium'
  if (/substack\.com|\bsubstack\b/.test(hay)) return 'substack'
  if (/dev\.to|\bdevto\b/.test(hay)) return 'devto'
  if (/twitter\.com|x\.com|\btwitter\b/.test(hay) || l === 'x') return 'x'
  return 'website'
}
